def make(variant):
    img = Image.new("RGB", (W + LEG_W, max(HS, 700)), (255, 255, 255))
    d = ImageDraw.Draw(img)
    common(d)
    (technic if variant == "техник" else city)(d)
    d.text((14, 10), "Джип по твоему рисунку: " + ("только Technic" if variant == "техник" else "Technic + City"),
           fill=(0, 0, 0), font=FT)
    d.text((14, 42), "Вид сбоку, перед слева. Зелёное - электроника, синее - кабина, красное - багажник.",
           fill=(70, 70, 70), font=F)
    x0 = W + 10
    d.line([(W, 0), (W, img.size[1])], fill=(200, 200, 200), width=2)
    for i, line in enumerate(LEGEND[variant]):
        d.text((x0, 20 + i * 30), line, fill=(0, 0, 0), font=FB if i == 0 else F)
    p = os.path.join(OUT, "схема-%s.png" % variant)
    img.save(p)
    return p


