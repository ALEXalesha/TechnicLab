import os

from PIL import Image, ImageDraw, ImageFont

OUT = os.path.dirname(os.path.abspath(__file__))
S = 1.15
Z0, Z1, Y0, Y1 = -500, 520, -530, 20
W = int((Z1 - Z0) * S)
HS = int((Y1 - Y0) * S)
LEG_W = 760
FRONT_Z, REAR_Z, WR = -300, 260, 71
LAYER = (-171, -281)
ROOF = -451

BLACK, DGREY, LGREY = (45, 48, 54), (110, 112, 118), (175, 178, 184)
YELLOW, RED, BLUE, WHITE = (245, 196, 0), (200, 30, 30), (40, 80, 200), (250, 250, 250)
GREEN_Z, BLUE_Z, RED_Z, HOOD_Z = (222, 244, 205), (218, 230, 255), (255, 226, 226), (236, 236, 236)
TRANS = (190, 225, 245)

F = ImageFont.truetype(r"C:\Windows\Fonts\arial.ttf", 15)
FB = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 19)
FT = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 24)


def P(z, y):
    return ((z - Z0) * S, (y - Y0) * S)


def rect(d, z0, z1, ya, yb, col, out=(40, 40, 40), w=2):
    d.rectangle([P(z0, ya), P(z1, yb)], fill=col, outline=out, width=w)


def beam_line(d, pts, col, w=9):
    d.line([P(*p) for p in pts], fill=col, width=w, joint="curve")
    for p in pts:
        x, y = P(*p)
        d.ellipse([x - 3, y - 3, x + 3, y + 3], fill=(230, 230, 230))


def num(d, z, y, n):
    x, yy = P(z, y)
    d.ellipse([x - 12, yy - 12, x + 12, yy + 12], fill=(255, 255, 255), outline=(0, 0, 0), width=2)
    d.text((x - 5 if n < 10 else x - 9, yy - 9), str(n), fill=(0, 0, 0), font=FB)


def common(d):
    d.line([P(Z0, 0), P(Z1, 0)], fill=(120, 90, 60), width=3)
    rect(d, -470, 470, LAYER[1], LAYER[0], GREEN_Z, out=None, w=0)
    rect(d, -200, 140, ROOF, LAYER[1], BLUE_Z, out=None, w=0)
    d.polygon([P(140, ROOF), P(300, ROOF), P(460, LAYER[1]), P(140, LAYER[1])], fill=RED_Z)
    rect(d, -470, -200, -321, LAYER[1], HOOD_Z, out=None, w=0)
    # электроника (настоящие габариты деталей из модели)
    for (z0, z1, ya, yb, col) in [(-440, -360, -255, -181, DGREY), (-330, -230, -301, -227, (225, 110, 100)),
                                  (-318, -248, -229, -161, DGREY), (-110, -10, -340, -201, LGREY),
                                  (-3, 123, -281, -161, DGREY), (140, 300, -261, -181, WHITE), (140, 300, -341, -261, WHITE)]:
        rect(d, z0, z1, ya, yb, col, out=(90, 90, 90))
    for i in range(4):                                        # поршни V8
        x, y = P(-322 + i * 24, -296)
        d.ellipse([x, y, x + 14, y + 10], fill=(200, 20, 20))
    rect(d, -60, 40, -291, -211, (120, 170, 230), out=(90, 90, 90))
    # колёса
    for z in (FRONT_Z, REAR_Z):
        x0, y0 = P(z - WR, -2 * WR)
        x1, y1 = P(z + WR, 0)
        d.ellipse([x0, y0, x1, y1], fill=(40, 40, 40))
        a0, b0 = P(z - 38, -109)
        a1, b1 = P(z + 38, -33)
        d.ellipse([a0, b0, a1, b1], fill=(200, 200, 200))


def technic(d):
    """Только Technic: всё из описи Алексея."""
    # 1 слой электроники: борта - кирпичи 1x16 (порог) и балки 5/L на y -171..-281
    beam_line(d, [(-200, -171), (100, -171)], BLACK)
    beam_line(d, [(-200, -281), (140, -281)], BLACK)
    for z in (-200, -60, 60):
        beam_line(d, [(z, -171), (z, -281)], BLACK, 7)
    num(d, -150, -230, 1)
    # 2 пол кабины - оси поперёк через борта (y -291)
    for z in range(-180, 121, 20):
        x, y = P(z, -291)
        d.ellipse([x - 4, y - 4, x + 4, y + 4], fill=BLACK)
    num(d, 40, -310, 2)
    # 3 капот - панели 3x11 (тёмно-серая) и 5x11 (чёрная) на гнутых 4x6
    beam_line(d, [(-460, -261), (-460, -321), (-200, -321)], LGREY, 8)
    d.line([P(-450, -323), P(-205, -323)], fill=BLACK, width=10)
    num(d, -330, -345, 3)
    # 4 лобовая стойка - гнутые 4x6 серые, наклон; 5 панель с рулём - шкив
    beam_line(d, [(-200, -291), (-200, -321), (-170, ROOF)], LGREY)
    d.ellipse([*P(-180, -381), *P(-170, -331)], fill=DGREY)
    num(d, -230, -400, 4)
    num(d, -150, -380, 5)
    # 6 сиденья - L 2x4 синяя + серая (2 модуля шириной) на полу кабины; серво - консоль между сиденьями
    beam_line(d, [(-100, -291), (-60, -291), (-60, -371)], BLUE, 11)
    num(d, -30, -355, 6)
    # 7 двери кабины вверх - рамка из L 3x5 (низ красный, верх жёлтый)
    beam_line(d, [(-195, -291), (-195, -411), (-20, -411), (-20, -291), (-195, -291)], RED, 6)
    beam_line(d, [(-195, -411), (-20, -411)], YELLOW, 6)
    num(d, -105, -455, 7)
    # 8 крыша - контур из осей + угловые соединители, поперечины
    d.line([P(-170, ROOF), P(300, ROOF)], fill=BLACK, width=5)
    for z in range(-150, 300, 60):
        x, y = P(z, ROOF)
        d.ellipse([x - 4, y - 4, x + 4, y + 4], fill=DGREY)
    num(d, 60, ROOF - 22, 8)
    # 9 стойка B - L 3x5 серая (граница кабины и багажника)
    beam_line(d, [(140, -291), (140, ROOF)], LGREY)
    num(d, 160, -400, 9)
    # 10 углубление багажника - пол из осей y -181 между лонжеронами, стенки - балки 5
    rect(d, 310, 450, LAYER[1], -176, (255, 205, 205), out=RED, w=3)
    for z in range(320, 441, 20):
        x, y = P(z, -181)
        d.ellipse([x - 4, y - 4, x + 4, y + 4], fill=BLACK)
    num(d, 380, -240, 10)
    # 11 дверь наклонная - гнутые 4x6 + 2 рамки 4x6 чёрные, актуатор с мотором M
    beam_line(d, [(300, ROOF), (460, -281)], LGREY, 10)
    d.line([P(320, ROOF + 20), P(440, -301)], fill=BLACK, width=16)
    d.line([P(160, -361), P(390, -371)], fill=(150, 150, 150), width=8)
    num(d, 400, -400, 11)
    # 12 арки - жёлтые L 3x5 над колёсами
    for z in (FRONT_Z, REAR_Z):
        beam_line(d, [(z - 70, -151), (z - 70, -191), (z + 70, -191), (z + 70, -151)], YELLOW, 8)
    num(d, REAR_Z, -215, 12)
    # 13 лебёдка - L-мотор, барабан, верёвка; фары - лампы на кирпичах
    d.line([P(-460, -171), P(-500, -171)], fill=(240, 130, 30), width=4)
    rect(d, -470, -455, -221, -201, WHITE)
    num(d, -486, -240, 13)


def city(d):
    """Technic + City: каркас тот же, City там, где Technic не даёт сплошной поверхности или узнаваемой мелочи."""
    technic(d)
    # пластины поверх: крыша, пол кабины, пол багажника, капот
    rect(d, -170, 300, ROOF - 8, ROOF + 4, (60, 60, 66), out=(20, 20, 20))
    num(d, 120, ROOF - 22, 14)
    rect(d, -195, 135, -297, -289, (90, 90, 96), out=(20, 20, 20))
    rect(d, 310, 450, -187, -179, (90, 90, 96), out=(20, 20, 20))
    num(d, 430, -215, 15)
    # кресла City вместо L 2x4, руль City
    rect(d, -110, -60, -311, -291, BLUE)
    rect(d, -70, -55, -381, -291, BLUE)
    d.ellipse([*P(-182, -371), *P(-168, -331)], outline=(20, 20, 20), width=4)
    num(d, -95, -340, 16)
    # прозрачные: лобовое стекло, боковые окна; фары и решётка
    d.polygon([P(-195, -301), P(-172, ROOF + 6), P(-160, ROOF + 6), P(-183, -301)], fill=TRANS)
    for (z0, z1) in ((-140, -70), (-50, 20), (170, 270)):
        rect(d, z0, z1, -436, -396, TRANS, out=(90, 120, 150))
    num(d, 220, -416, 17)
    num(d, -150, -380, 5)                                     # номера каркаса поверх стёкол
    num(d, -105, -455, 7)
    num(d, 160, -400, 9)
    rect(d, -472, -462, -241, -201, (250, 250, 200), out=(60, 60, 60))
    rect(d, -472, -462, -291, -251, (80, 80, 80), out=(30, 30, 30))
    num(d, -486, -300, 18)


