"""Схемы джипа по рисунку Алексея 24.11 21:52 (внизу слой электроники, сверху кабина и багажник с углублением,
задняя дверь наклонная) в двух вариантах: только Technic и Technic + City. Вид сбоку в масштабе (LDU, перед слева)
и список, из чего собрана каждая часть. Запуск: python scheme_v5.py -> схема-техник.png, схема-сити.png
"""
